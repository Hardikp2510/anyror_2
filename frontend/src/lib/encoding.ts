/**
 * Automatically detects and fixes CP437 and CP1252/Latin-1 mojibake strings back into authentic UTF-8 Gujarati.
 * Works transparently on strings, arrays, and nested objects.
 */
export function fixMojibake<T>(data: T): T {
  if (typeof data === "string") {
    // 1. Check for CP1252/Latin-1 mojibake (àª, à«, etc.)
    if (data.includes("àª") || data.includes("à«") || data.includes("à©") || data.includes("à¨")) {
      try {
        const bytes = new Uint8Array(data.length);
        for (let i = 0; i < data.length; i++) {
          const code = data.charCodeAt(i);
          bytes[i] = cp1252ReverseMap[code] ?? (code & 0xff);
        }
        const decoded = new TextDecoder("utf-8").decode(bytes);
        if (decoded && !decoded.includes("\uFFFD")) {
          return decoded as unknown as T;
        }
      } catch {}
    }

    // 2. Check for CP437 mojibake
    if (!data.includes("α") && !data.includes("¬") && !data.includes("½") && !data.includes("≡")) {
      return data;
    }
    try {
      const bytes = new Uint8Array(data.length);
      for (let i = 0; i < data.length; i++) {
        const ch = data[i];
        if (charToByte.has(ch)) {
          bytes[i] = charToByte.get(ch)!;
        } else {
          return data; // Not pure CP437 sequence, keep as is
        }
      }
      const decoded = new TextDecoder("utf-8").decode(bytes);
      // Validate that decoding resulted in clean Gujarati/valid characters
      if (decoded && !decoded.includes("\uFFFD")) {
        return decoded as unknown as T;
      }
      return data;
    } catch {
      return data;
    }
  }

  if (Array.isArray(data)) {
    return data.map((item) => fixMojibake(item)) as unknown as T;
  }

  if (data !== null && typeof data === "object") {
    const cleaned: Record<string, any> = {};
    for (const [key, value] of Object.entries(data)) {
      const cleanKey = fixMojibake(key);
      cleaned[cleanKey] = fixMojibake(value);
    }
    return cleaned as T;
  }

  return data;
}
